n = 0


def rep(old, new):
    global s, n
    assert s.count(old) == 1, (old[:90], s.count(old))
    s = s.replace(old, new)
    n += 1


def row(num, new):
    """Заменить строку таблицы задач с номером num целиком."""
    global s, n
    pat = re.compile(r'        <tr><td>%s</td>.*?</tr>' % re.escape(num), re.S)
    found = pat.findall(s)
    assert len(found) == 1, (num, len(found))
    s = pat.sub(lambda m: new, s, count=1)
    n += 1


